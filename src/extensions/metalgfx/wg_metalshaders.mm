"                                       constant float4 * pColor [[buffer(0)]],\n"
"                                       constant float & morphFactor [[buffer(5)]])\n"
"{\n"
"    float cov = lineCoverage(in);\n"
"    return writeColor(premul(lineColor(in, pColor)) * cov, cov, morphFactor);\n"
"}\n"
